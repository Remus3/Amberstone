"""RM-726 (a): the legacy dashboard page is KEPT on purpose, and the docs say so.

The repo review (KF, LEDGER 1703) filed `web/legacy_index.html` as "a retired
page still served". The s133 research re-probe found that mis-stated: the page
is not retired. `dashboard/routes_static.py` `_serve_index` serves it

  * at `?ui=legacy`, on request, and
  * as the FALLBACK whenever `web/index.html` fails to serve,

on purpose (its own comment: kept "in case the new one misbehaves during a
live match"). `tests/test_legacy_index_retired_gamepc_rm462.py` retires the
page's Game-PC wording, not the page. Neither `docs/ARCHITECTURE.md` nor
`docs/OPERATIONS.md` named the kept route, so the next reviewer would re-file
the same row. Acceptance (a): the kept route and its reason are recorded in
`docs/ARCHITECTURE.md`. Removing the page is an operator call, not this row.

The guard pins both halves against each other:

  * the doc records the page, both routes and the live-match reason, OUTSIDE
    the `archmap` block (that block is regenerated by `tools/gen_archmap.py`,
    so a line inside it would be erased by the next run);
  * the code still behaves as the doc says (a handler-level test of
    `_serve_index`, not a source grep). If the page is ever retired, these
    behaviour tests go red and the doc line must change in the same commit.

ASCII only (CLAUDE.md hard rule).
"""
from __future__ import annotations

import logging
import re
from pathlib import Path

import pytest

from dashboard import routes_static

_REPO_ROOT = Path(__file__).resolve().parents[1]
_ARCH = _REPO_ROOT / "docs" / "ARCHITECTURE.md"

_LEGACY_BODY = b"<!-- legacy sentinel -->"
_NEW_BODY = b"<html>new ui</html>"


def _arch_outside_generated_blocks() -> str:
    text = _ARCH.read_text(encoding="utf-8")
    # Drop every auto-generated block (archmap, phasejournal): a line there
    # is rewritten by tools/gen_archmap.py and cannot carry a record.
    return re.sub(
        r"<!-- (\w+):start\b.*?<!-- \1:end -->", "", text, flags=re.DOTALL,
    )


def _legacy_record() -> str:
    """The one paragraph / list item of ARCHITECTURE.md naming the page.

    Split on blank lines AND on list-item starts, so a key word in a
    neighbouring list item cannot satisfy the checks for this record.
    """
    body = _arch_outside_generated_blocks()
    blocks = [
        item
        for para in re.split(r"\n\s*\n", body)
        for item in re.split(r"\n(?=\s*(?:\d+\.|[-*])\s)", para)
    ]
    hits = [b for b in blocks if "web/legacy_index.html" in b]
    assert hits, (
        "docs/ARCHITECTURE.md (outside the generated archmap / phasejournal "
        "blocks) does not record the kept legacy page web/legacy_index.html "
        "(RM-726 (a))"
    )
    assert len(hits) == 1, (
        "web/legacy_index.html is recorded in more than one ARCHITECTURE.md "
        f"paragraph ({len(hits)}); keep one record so it cannot half-drift"
    )
    return hits[0]


def test_architecture_records_the_kept_legacy_page_and_both_routes():
    rec = _legacy_record()
    assert "?ui=legacy" in rec, "the record must name the ?ui=legacy route"
    assert re.search(r"fall\s*back|fallback", rec, re.IGNORECASE), (
        "the record must name the fallback when web/index.html fails"
    )
    assert "web/index.html" in rec, (
        "the record must name what the fallback stands in for (web/index.html)"
    )
    assert "dashboard/routes_static.py" in rec, (
        "the record must point at the serving code"
    )


def test_architecture_records_why_the_page_is_kept():
    rec = _legacy_record()
    assert re.search(r"live\s+(match|game)", rec, re.IGNORECASE), (
        "the record must carry the reason: a fallback if the new UI "
        "misbehaves during a live match"
    )
    assert re.search(r"operator", rec, re.IGNORECASE), (
        "the record must say removal is an operator call, so a later review "
        "does not re-file the page as a retired page still served"
    )


def test_architecture_record_is_ascii():
    rec = _legacy_record()
    assert rec.isascii(), "the RM-726 (a) record must be 7-bit ASCII"


class _StubHandler:
    def __init__(self, path: str) -> None:
        self.path = path
        self.sent: list[tuple[int, bytes, str]] = []

    def _send(self, code: int, body: bytes, ctype: str, *a, **k) -> None:
        self.sent.append((code, body, ctype))


@pytest.fixture
def _app_dir(tmp_path, monkeypatch):
    """A fake APP_DIR with a working web/index.html and a sentinel legacy page."""
    (tmp_path / "web").mkdir()
    (tmp_path / "web" / "index.html").write_bytes(_NEW_BODY)
    monkeypatch.setattr(routes_static, "APP_DIR", tmp_path)
    monkeypatch.setattr(routes_static, "legacy_index_html", lambda: _LEGACY_BODY)
    monkeypatch.setattr(routes_static, "inject_asset_hash", lambda b: b)
    return tmp_path


def test_root_serves_the_new_ui_not_the_legacy_page(_app_dir):
    h = _StubHandler("/")
    routes_static._serve_index(h)
    assert h.sent == [(200, _NEW_BODY, "text/html; charset=utf-8")]


@pytest.mark.parametrize("path", ["/?ui=legacy", "/index.html?ui=legacy"])
def test_ui_legacy_serves_the_legacy_page_even_when_the_new_ui_works(
    _app_dir, path,
):
    h = _StubHandler(path)
    routes_static._serve_index(h)
    assert h.sent == [(200, _LEGACY_BODY, "text/html; charset=utf-8")]


def test_a_failing_new_ui_falls_back_to_the_legacy_page(_app_dir, caplog):
    (_app_dir / "web" / "index.html").unlink()
    h = _StubHandler("/")
    with caplog.at_level(logging.WARNING, logger="rc.web_dashboard"):
        routes_static._serve_index(h)
    assert h.sent == [(200, _LEGACY_BODY, "text/html; charset=utf-8")]
    assert any(
        r.levelno == logging.WARNING and "falling back to legacy" in r.getMessage()
        for r in caplog.records
    ), "the fallback must log a warning (the ARCHITECTURE.md record says so)"


def test_the_real_legacy_page_is_still_tracked_and_loadable():
    page = _REPO_ROOT / "web" / "legacy_index.html"
    assert page.is_file(), (
        "web/legacy_index.html is gone: the RM-726 (a) ARCHITECTURE.md "
        "record and dashboard/routes_static.py must change with it"
    )
    assert b"<html" in page.read_bytes()[:4096].lower()
