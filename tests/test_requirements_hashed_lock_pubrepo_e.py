"""PUBREPO e: requirements.txt is a HASHED lock generated from requirements.in.

requirements.in holds the human-edited top-level pins (exact `==`, no
hashes). requirements.txt is generated from it by `uv pip compile
--universal --python-version 3.11 --generate-hashes`, so every package,
transitive ones included, carries an exact pin and the sha256 of every file
PyPI serves for it, and `pip install -r requirements.txt` (install.bat) runs
in hash-checking mode on every supported interpreter: the embedded 3.11
runtime, 3.12 (CI, README floor), 3.13 and 3.14 (the operator's runtime).

These guards catch the drift a hand edit or a partial bump leaves behind:
an .in pin the lock does not carry at that version, a lock entry without a
hash, a header that no longer names the command, a machine path in the
generated header, or a CI install set that still includes the hashed file
instead of the .in. requirements.lock (a stale box `pip freeze`) is retired:
the hashed requirements.txt is the lock now.
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ_IN = ROOT / "requirements.in"
REQ_TXT = ROOT / "requirements.txt"
CI_DIR = ROOT / ".github" / "ci"
CI_YML = ROOT / ".github" / "workflows" / "ci.yml"

COMPILE_CMD = ("uv pip compile requirements.in --universal --python-version 3.11 "
               "--generate-hashes --output-file requirements.txt")

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s;\\]+)")
_HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}\b")


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _logical_lines(text: str) -> list[str]:
    """Join backslash continuations; drop comments and blank lines."""
    out, buf = [], ""
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].rstrip() if not raw.lstrip().startswith("--hash") else raw.rstrip()
        if line.endswith("\\"):
            buf += line[:-1] + " "
            continue
        buf += line
        if buf.strip():
            out.append(buf.strip())
        buf = ""
    if buf.strip():
        out.append(buf.strip())
    return out


def _in_pins() -> dict[str, str]:
    pins = {}
    for line in _logical_lines(REQ_IN.read_text(encoding="utf-8")):
        m = _PIN.match(line)
        assert m and line == m.group(0), f"requirements.in line is not a bare exact pin: {line!r}"
        pins[_norm(m.group(1))] = m.group(2)
    assert pins, "requirements.in yielded no pins - the parser is wrong, not the file"
    return pins


def _lock_entries() -> list[tuple[str, str, str]]:
    """(normalized name, version, whole logical line) per requirements.txt entry."""
    out = []
    for line in _logical_lines(REQ_TXT.read_text(encoding="utf-8")):
        m = _PIN.match(line)
        assert m, f"requirements.txt entry is not an exact pin: {line!r}"
        out.append((_norm(m.group(1)), m.group(2), line))
    assert out, "requirements.txt yielded no entries - the parser is wrong, not the file"
    return out


def test_requirements_in_is_unhashed_exact_pins():
    text = REQ_IN.read_text(encoding="utf-8")
    assert "--hash" not in text
    assert len(_in_pins()) >= 9


def test_every_lock_entry_is_pinned_and_hashed():
    for name, _ver, line in _lock_entries():
        assert _HASH.search(line), f"requirements.txt pins {name} without a hash"


def test_every_in_pin_is_in_the_lock_at_the_same_version():
    lock: dict[str, set[str]] = {}
    for name, ver, _line in _lock_entries():
        lock.setdefault(name, set()).add(ver)
    for name, ver in _in_pins().items():
        assert lock.get(name) == {ver}, (
            f"requirements.in pins {name}=={ver} but requirements.txt carries "
            f"{sorted(lock.get(name, ()))} - regenerate it: {COMPILE_CMD}")


def test_both_headers_name_the_exact_compile_command():
    assert COMPILE_CMD in REQ_IN.read_text(encoding="utf-8")
    head = REQ_TXT.read_text(encoding="utf-8").splitlines()[:2]
    assert head[0].startswith("# This file was autogenerated by uv"), head
    assert head[1].strip("# ").strip() == COMPILE_CMD, head


def test_generated_files_carry_no_machine_path_and_are_ascii_lf():
    for path in (REQ_IN, REQ_TXT):
        raw = path.read_bytes()
        raw.decode("ascii")  # raises on any non-ASCII byte
        assert b"\r" not in raw, f"{path.name} must be LF-only"
        text = raw.decode("ascii")
        assert not re.search(r"\b[A-Za-z]:[\\/]", text), f"{path.name} names a drive path"
        assert "\\Users\\" not in text and "/Users/" not in text and "/home/" not in text


def test_ci_install_sets_include_the_in_not_the_hashed_lock():
    ins = sorted(CI_DIR.glob("requirements-*.in"))
    assert ins, "vacuous: no .github/ci/requirements-*.in"
    for path in ins:
        refs = re.findall(r"^-[rc]\s+(\S+)", path.read_text(encoding="utf-8"), re.M)
        assert "../../requirements.in" in refs, f"{path.name} does not include ../../requirements.in"
        assert "../../requirements.txt" not in refs, f"{path.name} still includes the hashed lock"


def test_ci_agree_step_reads_the_in():
    text = CI_YML.read_text(encoding="utf-8")
    assert 'root = pins("requirements.in")' in text
    assert 'root = pins("requirements.txt")' not in text


def test_requirements_lock_is_retired():
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--", "requirements.lock"],
                         capture_output=True, text=True, check=True).stdout
    assert out.strip() == "", "requirements.lock is tracked again - the hashed requirements.txt is the lock"


def test_logical_line_parser_joins_continuations():
    text = ("# header\nfoo==1.0 ; sys_platform == 'win32' \\\n"
            "    --hash=sha256:" + "a" * 64 + " \\\n    --hash=sha256:" + "b" * 64 + "\n"
            "    # via -r requirements.in\nbar==2.0 \\\n    --hash=sha256:" + "c" * 64 + "\n")
    lines = _logical_lines(text)
    assert len(lines) == 2
    assert lines[0].startswith("foo==1.0 ; sys_platform == 'win32'")
    assert len(_HASH.findall(lines[0])) == 2
    assert _PIN.match(lines[1]).group(2) == "2.0"
